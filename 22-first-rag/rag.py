"""RAG-пайплайн дня: вопрос → поиск чанков → объединение с вопросом → сообщения для LLM.

Здесь только сборка промпта. Вызов модели и учёт токенов — в agent.py, поиск — в index.py.
Оба режима получают одинаковую базовую инструкцию, чтобы разница в ответах шла от
контекста, а не от формулировки просьбы.
"""

BASE = ("Ты — справочник по действующей Конституции Российской Федерации. "
        "Отвечай по-русски, кратко: 2–5 предложений. Называй номера статей, на которые опираешься.")

PLAIN_SYSTEM = BASE

RAG_SYSTEM = BASE + """

Ниже в сообщении пользователя — фрагменты официального текста Конституции (kremlin.ru,
с поправками 2020 года), найденные поиском по вопросу. Правила:
- отвечай только по этим фрагментам, не по памяти; если память с ними расходится — прав текст;
- после каждого утверждения ставь ссылку на фрагмент в квадратных скобках: [ст.81];
- если во фрагментах ответа нет, так и скажи: «В найденных статьях ответа нет» — и не додумывай."""

RAG_USER = """Фрагменты Конституции:

<<CONTEXT>>

Вопрос: <<QUESTION>>"""


def context_block(hits):
    """Чанки → нумерованный текстовый блок. Метка [ст.N] — то, на что модель ссылается."""
    blocks = []
    for hit in hits:
        chapter = hit["chapter"] or "Заключительные и переходные положения"
        blocks.append(f"[{hit['chunk_id'].split('#')[0]}] {chapter}\n{hit['text']}")
    return "\n\n---\n\n".join(blocks)


def messages(question, hits=None):
    """Без hits — обычный запрос к модели, с hits — RAG."""
    if hits is None:
        return [{"role": "system", "content": PLAIN_SYSTEM},
                {"role": "user", "content": question}]
    # .replace, а не .format: в тексте статей бывают фигурные скобки и кавычки.
    user = RAG_USER.replace("<<CONTEXT>>", context_block(hits)).replace("<<QUESTION>>", question)
    return [{"role": "system", "content": RAG_SYSTEM},
            {"role": "user", "content": user}]
